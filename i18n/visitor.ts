export const VISITOR_COPY: Record<InterfaceLanguage, Record<VisitorCopyKey, string>> = { en: EN, ne: NE };

/** Typed dictionaries make a missing English or Nepali key a compile error. */
export function visitorCopy(language: InterfaceLanguage, key: VisitorCopyKey): string {
  return VISITOR_COPY[language][key];
}

/** Interpolate a translated template while requiring every English placeholder. */
export function formatVisitorCopy<Key extends VisitorCopyKey>(
  language: InterfaceLanguage,
  key: Key,
  values: VisitorCopyValues<Key>,
): string {
  const template = visitorCopy(language, key);
  return template.replace(/\{([^}]+)\}/g, (placeholder, name: string) => {
    const value = (values as Record<string, string | number>)[name];
    return value == null ? placeholder : String(value);
  });
}
