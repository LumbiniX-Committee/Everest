// Bundles the map's two browser libraries into the app, so the map no longer
// depends on a CDN at runtime: it opens offline, and an outage elsewhere can't
// blank it. Re-run after changing either pinned version in package.json.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const modules = new URL('../node_modules/', import.meta.url);
const read = (path) => readFileSync(new URL(path, modules), 'utf8');

// A literal "</script" inside a script ends it early, so escape any occurrence.
const safe = (code) => code.replace(/<\/script/gi, '<\\/script');

const versions = {
  maplibre: JSON.parse(read('maplibre-gl/package.json')).version,
  three: JSON.parse(read('three/package.json')).version,
};

const body = `// GENERATED by tools/vendor-map.mjs. Do not edit.
// maplibre-gl ${versions.maplibre}, three ${versions.three}. Both are bundled so the map works offline.
export const MAPLIBRE_JS = ${JSON.stringify(safe(read('maplibre-gl/dist/maplibre-gl.js')))};
export const MAPLIBRE_CSS = ${JSON.stringify(read('maplibre-gl/dist/maplibre-gl.css'))};
export const THREE_JS = ${JSON.stringify(safe(read('three/build/three.min.js')))};
`;

writeFileSync(new URL('../components/map/vendor.generated.ts', import.meta.url), body);

// The 3D monument viewer. Its standalone build carries its own copy of three.js,
// and it declares a newer three as a peer, which would conflict with the map's.
// So it isn't a dependency: install it only to refresh this file, then remove it.
//   npm i --no-save --legacy-peer-deps @google/model-viewer@4.4.0 && npm run vendor:map && npm ci
if (!existsSync(new URL('@google/model-viewer/package.json', modules))) {
  console.log('model-viewer not installed; keeping components/models/vendor.generated.ts as it is');
  process.exit(0);
}
const modelViewerVersion = JSON.parse(read('@google/model-viewer/package.json')).version;
writeFileSync(
  new URL('../components/models/vendor.generated.ts', import.meta.url),
  `// GENERATED by tools/vendor-map.mjs. Do not edit.\n// @google/model-viewer ${modelViewerVersion}, bundled so 3D views work offline.\nexport const MODEL_VIEWER_JS = ${JSON.stringify(safe(read('@google/model-viewer/dist/model-viewer-umd.min.js')))};\n`,
);
console.log(`vendored maplibre-gl ${versions.maplibre}, three ${versions.three} and model-viewer`);
