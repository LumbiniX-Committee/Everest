// tools/gen-3d-web.mjs
//
// Feeds the 3D pages of the app and the website from one source:
//   seed/scans.json            → data/generated/scans.ts, landing/lib/generated/scans.ts
//   data/generated/models.ts   → landing/lib/generated/models.ts (our schematic models)
//   components/models/vendor.generated.ts → landing/public/vendor/model-viewer.min.js
//
//   node --experimental-strip-types tools/gen-3d-web.mjs           write
//   node --experimental-strip-types tools/gen-3d-web.mjs --check   fail if stale
//
// The website serves model-viewer itself, the same build the app bundles, so
// a visitor's browser does not fetch it from a third-party CDN.
import { readFileSync, writeFileSync } from 'node:fs';

const ROOT = new URL('../', import.meta.url);
const read = (path) => readFileSync(new URL(path, ROOT), 'utf8');
const { scans } = JSON.parse(read('seed/scans.json'));
const { MODELS } = await import(new URL('data/generated/models.ts', ROOT).href);
const { MODEL_VIEWER_JS } = await import(new URL('components/models/vendor.generated.ts', ROOT).href);

const header = (source) => `/**\n * GENERATED by tools/gen-3d-web.mjs from ${source}. Do not edit.\n */\n`;
const scanType = `export type Scan = {
  id: string;
  /** Our name for it. \`title\` is the creator's own. */
  label: string;
  title: string;
  creator: string;
  creatorUrl: string;
  viewerUrl: string;
  licence: string;
  /** Creative Commons. Otherwise it is only ever shown in Sketchfab's player. */
  openLicence: boolean;
  kind: string;
  captured: string | null;
  published: string | null;
  thumbnail: string;
  /** Site or place ids this scan shows. */
  targets: string[];
  note: string;
};
`;
const scansTs = `${header('seed/scans.json')}${scanType}
export const SCANS: Scan[] = ${JSON.stringify(scans, null, 1)};

/** The Sketchfab player for a scan. Loaded only when someone asks; \`dnt=1\` asks it not to track. */
export function scanEmbedUrl(id: string, autostart = true): string {
  return \`https://sketchfab.com/models/\${id}/embed?autostart=\${autostart ? 1 : 0}&dnt=1&ui_theme=dark&ui_infos=0&ui_watermark_link=1&preload=1\`;
}

export function scansFor(...ids: (string | undefined)[]): Scan[] {
  const wanted = new Set(ids.filter(Boolean));
  return SCANS.filter((scan) => scan.targets.some((target) => wanted.has(target)));
}
`;
const models = MODELS.map(({ id, title, targets, kind, bytes, sources, hotspots }) => ({ id, title, targets, kind, bytes, sources, hotspots }));
const modelsTs = `${header('data/generated/models.ts')}export type WebModel = {
  id: string;
  title: string;
  targets: string[];
  kind: 'schematic';
  bytes: number;
  sources: { title: string; url: string }[];
  hotspots: { label: string; note: string; position: number[] }[];
};

/** Served from /models/<id>.gltf. */
export const MODELS: WebModel[] = ${JSON.stringify(models, null, 1)};
`;

const outputs = [
  ['data/generated/scans.ts', scansTs],
  ['landing/lib/generated/scans.ts', scansTs],
  ['landing/lib/generated/models.ts', modelsTs],
  ['landing/public/vendor/model-viewer.min.js', MODEL_VIEWER_JS],
];

if (process.argv.includes('--check')) {
  const stale = outputs.filter(([path, body]) => {
    try {
      return read(path) !== body;
    } catch {
      return true;
    }
  });
  if (stale.length) {
    console.error(`stale: ${stale.map(([p]) => p).join(', ')}; run node --experimental-strip-types tools/gen-3d-web.mjs`);
    process.exit(1);
  }
  console.log(`3D web data up to date: ${scans.length} scans, ${models.length} models`);
} else {
  for (const [path, body] of outputs) writeFileSync(new URL(path, ROOT), body);
  console.log(`wrote ${scans.length} scans, ${models.length} models, model-viewer`);
}
