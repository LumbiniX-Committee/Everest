// tools/vendor-gltf-loader.mjs
//
// Packages three.js's GLTFLoader for the map page, which runs three.js as a
// global script (THREE) rather than as modules. three 0.160 ships the loader
// only as an ES module that imports from 'three', and no bundler is installed
// here, so this rewrites those imports to read from the global instead:
//
//   import { A, B } from 'three'            → const { A, B } = THREE;
//   import { toTrianglesDrawMode } from …   → the one helper, inlined
//   export { GLTFLoader }                   → THREE.GLTFLoader = GLTFLoader
//
//   node tools/vendor-gltf-loader.mjs
//
// Output: components/map/gltfLoader.generated.ts. Re-run after upgrading three.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

// three's package exports hide package.json, so read it by path.
const threeDir = fileURLToPath(new URL('../node_modules/three/', import.meta.url));
const version = JSON.parse(readFileSync(join(threeDir, 'package.json'), 'utf8')).version;
const loader = readFileSync(join(threeDir, 'examples/jsm/loaders/GLTFLoader.js'), 'utf8');
const utils = readFileSync(join(threeDir, 'examples/jsm/utils/BufferGeometryUtils.js'), 'utf8');

// The helper GLTFLoader imports, cut out whole: from its declaration to the
// first closing brace at the start of a line.
const start = utils.indexOf('function toTrianglesDrawMode(');
const end = utils.indexOf('\n}\n', start) + 3;
if (start < 0 || end < 3) throw new Error('toTrianglesDrawMode not found; three changed shape');
const helper = utils.slice(start, end);

const threeImport = /import\s*\{([^}]*)\}\s*from\s*'three';/;
const match = loader.match(threeImport);
if (!match) throw new Error("GLTFLoader no longer imports from 'three' in one statement");
const names = match[1].split(',').map((n) => n.trim()).filter(Boolean);

let body = loader
  .replace(threeImport, '')
  .replace(/import\s*\{\s*toTrianglesDrawMode\s*\}\s*from\s*'[^']+';/, '')
  .replace(/export\s*\{\s*GLTFLoader\s*\};?/, '');
if (/^\s*import\s/m.test(body) || /^\s*export\s/m.test(body)) throw new Error('GLTFLoader has imports or exports this script does not handle');

const code = `(function () {
  if (typeof THREE === 'undefined' || THREE.GLTFLoader) return;
  const { ${[...new Set([...names, 'TrianglesDrawMode', 'TriangleFanDrawMode', 'TriangleStripDrawMode'])].join(', ')} } = THREE;
  ${helper}
  ${body}
  THREE.GLTFLoader = GLTFLoader;
})();
`;

// Safe inside an inline <script>.
const safe = code.replace(/<\/script/gi, '<\\/script');
writeFileSync(
  new URL('../components/map/gltfLoader.generated.ts', import.meta.url),
  `// GENERATED by tools/vendor-gltf-loader.mjs from three ${version}. Do not edit.\n// GLTFLoader for the map page, which loads three.js as a global script.\nexport const GLTF_LOADER_JS = ${JSON.stringify(safe)};\n`,
);
console.log(`GLTFLoader from three ${version}: ${names.length} names, ${(safe.length / 1024).toFixed(0)} KB`);
