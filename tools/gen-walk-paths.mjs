// tools/gen-walk-paths.mjs
//
// The demo walks follow mapped footpaths, not straight lines through houses.
// For every leg of every walk in data/demoWalks.ts this asks a pedestrian
// router (the same public Valhalla the app's directions use) for the path,
// and writes them all to data/generated/walkPaths.ts so the walk works offline
// and is the same walk every time.
//
//   node --experimental-strip-types --no-warnings tools/gen-walk-paths.mjs
//
// Run it after changing a walk or a site's coordinate. A leg the router cannot
// answer is left out, and the walker falls back to a straight line for it.
import { writeFileSync } from 'node:fs';

const ROOT = new URL('../', import.meta.url);
const { WALK_DEFINITIONS } = await import(new URL('data/demoWalks.ts', ROOT).href);
const { demoSites } = await import(new URL('data/generated/sites.ts', ROOT).href);
const ENDPOINT = process.env.ROUTING_URL || 'https://valhalla1.openstreetmap.de/route';

const site = (id) => demoSites.find((s) => s.id === id)?.coordinate;
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

/** Valhalla's polyline6. */
function decode(str) {
  let index = 0, lat = 0, lng = 0;
  const out = [];
  while (index < str.length) {
    for (const which of [0, 1]) {
      let result = 0, shift = 0, b;
      do { b = str.charCodeAt(index++) - 63; result |= (b & 0x1f) << shift; shift += 5; } while (b >= 0x20);
      const d = result & 1 ? ~(result >> 1) : result >> 1;
      if (which === 0) lat += d; else lng += d;
    }
    out.push([Math.round(lng) / 1e6, Math.round(lat) / 1e6]);
  }
  return out;
}

async function route(a, b) {
  for (let attempt = 0; attempt < 3; attempt += 1) {
    const res = await fetch(ENDPOINT, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json', 'User-Agent': 'saksi-walk-paths/1.0' },
      body: JSON.stringify({
        locations: [{ lat: a.latitude, lon: a.longitude }, { lat: b.latitude, lon: b.longitude }],
        costing: 'pedestrian',
        directions_type: 'none',
      }),
    }).catch(() => null);
    if (res?.ok) {
      const shape = (await res.json()).trip?.legs?.[0]?.shape;
      return shape ? decode(shape) : null;
    }
    if (res && res.status === 400) return null; // no route between these points
    await sleep(3000);
  }
  return null;
}

const paths = {};
let asked = 0, missing = 0;
for (const walk of WALK_DEFINITIONS) {
  let from = null;
  for (const [i, leg] of walk.legs.entries()) {
    if ('start' in leg) { from = leg.start; continue; }
    if ('circle' in leg) continue;
    const to = site(leg.at);
    if (!to) continue;
    if (from && (Math.abs(from.latitude - to.latitude) > 1e-6 || Math.abs(from.longitude - to.longitude) > 1e-6)) {
      asked += 1;
      const path = await route(from, to);
      if (path && path.length >= 2) paths[`${walk.id}:${i}`] = path;
      else { missing += 1; console.warn(`no path for ${walk.id} leg ${i} (to ${leg.at})`); }
      await sleep(1100); // the public server asks for one request a second
    }
    from = to;
  }
}

const body = `/**
 * GENERATED by tools/gen-walk-paths.mjs from data/demoWalks.ts. Do not edit.
 *
 * The mapped footpath for each walking leg of the demo walks, keyed
 * "<walk id>:<leg index>", as [longitude, latitude] pairs. Routed by Valhalla
 * (pedestrian) over OpenStreetMap data, © OpenStreetMap contributors, ODbL.
 */
export const WALK_PATHS: Record<string, [number, number][]> = ${JSON.stringify(paths)};
`;
writeFileSync(new URL('data/generated/walkPaths.ts', ROOT), body);
console.log(`${Object.keys(paths).length} of ${asked} legs routed${missing ? `, ${missing} left straight` : ''}`);
