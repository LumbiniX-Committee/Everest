export function normalizeVisitorLiteral(value: string): string {
  return value.replace(/\s+/g, ' ').trim();
}

export function visitorLiteralCopy(language: InterfaceLanguage, value: string): string {
  const normalized = normalizeVisitorLiteral(value);
  if (!normalized || language === 'en') return normalized || value;
  return NEPALI_UI_LITERALS[normalized as keyof typeof NEPALI_UI_LITERALS] ?? normalized;
}

export function localizeVisitorNode(language: InterfaceLanguage, node: ReactNode): ReactNode {
  if (typeof node === 'string') return visitorLiteralCopy(language, node);
  if (Array.isArray(node)) return node.map((child) => localizeVisitorNode(language, child));
  return node;
}
