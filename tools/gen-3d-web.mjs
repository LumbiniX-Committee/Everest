// tools/gen-3d-web.mjs
//
// Feeds the 3D pages of the app and the website from one source:
//   seed/scans.json            → data/generated/scans.ts, landing/lib/generated/scans.ts
//   data/mapScans.ts           → landing/lib/generated/models.ts (real scans and our detailed models)
//   components/models/vendor.generated.ts → landing/public/vendor/model-viewer.min.js
//
//   node --experimental-strip-types tools/gen-3d-web.mjs           write
//   node --experimental-strip-types tools/gen-3d-web.mjs --check   fail if stale
//
// The website serves model-viewer itself, the same build the app bundles, so
// a visitor's browser does not fetch it from a third-party CDN.
import { readFileSync, writeFileSync } from 'node:fs';

const ROOT = new URL('../', import.meta.url);
const read = (path) => readFileSync(new URL(path, ROOT), 'utf8');
const { scans } = JSON.parse(read('seed/scans.json'));
const { MAP_SCANS } = await import(new URL('data/mapScans.ts', ROOT).href);
const { MODEL_VIEWER_JS } = await import(new URL('components/models/vendor.generated.ts', ROOT).href);

const header = (source) => `/**\n * GENERATED by tools/gen-3d-web.mjs from ${source}. Do not edit.\n */\n`;
const scanType = `export type Scan = {
  id: string;
  /** Our name for it. \`title\` is the creator's own. */
  label: string;
  title: string;
  creator: string;
  creatorUrl: string;
  viewerUrl: string;
  licence: string;
  /** Creative Commons. Otherwise it is only ever shown in Sketchfab's player. */
  openLicence: boolean;
  kind: string;
  captured: string | null;
  published: string | null;
  thumbnail: string;
  /** About 1280 px wide, for a large stage. */
  poster: string;
  /** Site or place ids this scan shows. */
  targets: string[];
  /** Where it stands on the map: an OpenStreetMap point, a pin rather than a survey. */
  at: { latitude: number; longitude: number };
  note: string;
};
`;
const scansTs = `${header('seed/scans.json')}${scanType}
export const SCANS: Scan[] = ${JSON.stringify(scans, null, 1)};

/** The Sketchfab player for a scan. Loaded only when someone asks; \`dnt=1\` asks it not to track. */
export function scanEmbedUrl(id: string, autostart = true): string {
  return \`https://sketchfab.com/models/\${id}/embed?autostart=\${autostart ? 1 : 0}&dnt=1&ui_theme=dark&ui_infos=0&ui_watermark_link=1&preload=1&autospin=0.12\`;
}

export function scansFor(...ids: (string | undefined)[]): Scan[] {
  const wanted = new Set(ids.filter(Boolean));
  return SCANS.filter((scan) => scan.targets.some((target) => wanted.has(target)));
}

/** One map pin per place that has scans: scans at the same point share it. */
export type ScanSpot = { key: string; latitude: number; longitude: number; label: string; scanIds: string[] };

export function scanSpots(): ScanSpot[] {
  const spots = new Map<string, ScanSpot>();
  for (const scan of SCANS) {
    const key = \`\${scan.at.latitude.toFixed(5)},\${scan.at.longitude.toFixed(5)}\`;
    const spot = spots.get(key);
    if (spot) spot.scanIds.push(scan.id);
    else spots.set(key, { key, latitude: scan.at.latitude, longitude: scan.at.longitude, label: scan.label, scanIds: [scan.id] });
  }
  return [...spots.values()];
}
`;
// The website shows what the map shows: real scans and our detailed models,
// never the schematic ones. One file standing in two places is listed once.
const seen = new Set();
const models = MAP_SCANS.filter((m) => {
  const file = m.modelled ? `modelled/${m.file ?? m.id}.glb` : `scans/${m.id}.glb`;
  if (seen.has(file)) return false;
  seen.add(file);
  return true;
}).map((m) => ({
  id: m.id,
  title: m.file ? m.title.replace(/^[^,]+/, 'Pratappur and Anantapur Shikhara') : m.title,
  kind: m.modelled ? 'modelled' : 'scan',
  file: m.modelled ? `modelled/${m.file ?? m.id}.glb` : `scans/${m.id}.glb`,
  creator: m.creator,
  licence: m.licence,
  bytes: m.bytes,
  source: m.modelled
    ? { title: `OpenStreetMap ${m.osm}`, url: `https://www.openstreetmap.org/${m.osm}` }
    : { title: `${m.title} by ${m.creator}, on Sketchfab`, url: `https://sketchfab.com/3d-models/${m.scanId}` },
}));
const modelsTs = `${header('data/mapScans.ts')}export type WebModel = {
  id: string;
  title: string;
  /** A real scan (photogrammetry by its creator) or our own model, built in Blender from photos and OpenStreetMap. */
  kind: 'scan' | 'modelled';
  /** Path under /models/. */
  file: string;
  creator: string;
  licence: string;
  bytes: number;
  source: { title: string; url: string };
};

export const MODELS: WebModel[] = ${JSON.stringify(models, null, 1)};
`;

const outputs = [
  ['data/generated/scans.ts', scansTs],
  ['landing/lib/generated/scans.ts', scansTs],
  ['landing/lib/generated/models.ts', modelsTs],
  ['landing/public/vendor/model-viewer.min.js', MODEL_VIEWER_JS],
];

if (process.argv.includes('--check')) {
  const stale = outputs.filter(([path, body]) => {
    try {
      return read(path) !== body;
    } catch {
      return true;
    }
  });
  if (stale.length) {
    console.error(`stale: ${stale.map(([p]) => p).join(', ')}; run node --experimental-strip-types tools/gen-3d-web.mjs`);
    process.exit(1);
  }
  console.log(`3D web data up to date: ${scans.length} scans, ${models.length} models`);
} else {
  for (const [path, body] of outputs) writeFileSync(new URL(path, ROOT), body);
  console.log(`wrote ${scans.length} scans, ${models.length} models, model-viewer`);
}
