// Turns seed/places.json and seed/fees.json into typed app modules. Run after
// build-places.mjs; validate-seed fails if the output is stale.
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../../', import.meta.url);
const read = (path) => JSON.parse(readFileSync(new URL(path, root), 'utf8'));
const places = read('seed/places.json');
const fees = read('seed/fees.json');

const routeId = (id) => id.replace(/[:/]/g, '-');

const out = places.places.map((p) => ({
  id: routeId(p.id),
  name: p.name,
  nameNepali: p.nameNe,
  description: p.description,
  category: p.category,
  coordinate: { latitude: Number(p.lat.toFixed(6)), longitude: Number(p.lon.toFixed(6)) },
  hub: p.hub,
  hours: p.hours,
  website: p.website,
  wheelchair: p.wheelchair,
  wikipedia: p.wikipedia,
  wikidata: p.wikidata,
  image: p.image,
  feeId: p.feeId ?? null,
  sources: p.sources,
}));

const header = '// GENERATED by tools/data/gen-places.mjs from seed/places.json and seed/fees.json. Do not edit.\n';
writeFileSync(
  new URL('data/generated/places.ts', root),
  `${header}import type { EntryFee, Place } from '@/types';\n\n` +
    `/** ${places.licence.osm} ${places.licence.wikidata} */\n` +
    `export const PLACES: Place[] = ${JSON.stringify(out)};\n\n` +
    `export const ENTRY_FEES: EntryFee[] = ${JSON.stringify(fees.fees.map(({ siteIds, matchPlaceNames, ...fee }) => fee))};\n\n` +
    `/** Which curated sites each fee covers. */\n` +
    `export const FEE_SITE_IDS: Record<string, string[]> = ${JSON.stringify(Object.fromEntries(fees.fees.filter((f) => f.siteIds).map((f) => [f.id, f.siteIds])))};\n\n` +
    `export const FEES_SOURCE = ${JSON.stringify({ ...fees.source, lastChecked: fees.lastChecked })} as const;\n`,
);
console.log(`places module: ${out.length} places, ${fees.fees.length} fees`);
